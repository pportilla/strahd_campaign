// Translate range (handles "X feet" patterns)
export function translateRange(range: string): string {
    if (RANGE_TRANSLATIONS[range]) {
        return RANGE_TRANSLATIONS[range];
    }

    // Handle "X feet" patterns
    const feetMatch = range.match(/^(\d+)\s*feet?$/i);
    if (feetMatch) {
        return `${feetMatch[1]} pies`;
    }

    // Handle "X miles" patterns
    const milesMatch = range.match(/^(\d+)\s*miles?$/i);
    if (milesMatch) {
        return `${milesMatch[1]} millas`;
    }

    // Handle self with area patterns like "Self (30-foot radius)"
    const selfAreaMatch = range.match(/^Self\s*\((\d+)-foot\s*(\w+)\)/i);
    if (selfAreaMatch) {
        const size = selfAreaMatch[1];
        const type = AOE_TYPE_TRANSLATIONS[selfAreaMatch[2].toLowerCase()] || selfAreaMatch[2];
        return `Personal (${type} de ${size} pies)`;
    }

    return range;
}

// Translate duration
export function translateDuration(duration: string): string {
    if (DURATION_TRANSLATIONS[duration]) {
        return DURATION_TRANSLATIONS[duration];
    }

    // Handle concentration patterns
    if (duration.toLowerCase().startsWith('concentration')) {
        return duration
            .replace(/concentration,?\s*/i, 'Concentración, ')
            .replace(/up to/i, 'hasta')
            .replace(/(\d+)\s*minute/i, '$1 minuto')
            .replace(/(\d+)\s*hour/i, '$1 hora')
            .replace(/(\d+)\s*round/i, '$1 asalto');
    }

    return duration
        .replace(/(\d+)\s*minutes?/i, '$1 minutos')
        .replace(/(\d+)\s*hours?/i, '$1 horas')
        .replace(/(\d+)\s*days?/i, '$1 días')
        .replace(/(\d+)\s*rounds?/i, '$1 asaltos');
}

// Translate casting time
export function translateCastingTime(castingTime: string): string {
    if (CASTING_TIME_TRANSLATIONS[castingTime]) {
        return CASTING_TIME_TRANSLATIONS[castingTime];
    }

    return castingTime
        .replace(/(\d+)\s*action/i, '$1 acción')
        .replace(/(\d+)\s*bonus action/i, '$1 acción adicional')
        .replace(/(\d+)\s*reaction/i, '$1 reacción')
        .replace(/(\d+)\s*minutes?/i, '$1 minutos')
        .replace(/(\d+)\s*hours?/i, '$1 horas');
}

// Translate damage type
export function translateDamageType(damageType: string): string {
    return DAMAGE_TYPE_TRANSLATIONS[damageType.toLowerCase()] || damageType;
}
